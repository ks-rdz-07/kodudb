// SQL for the Data explorer's table actions: modify (rename, columns), archive, restore and delete.
import { qi, ql } from './quote.mjs'

/** Archived tables live here: out of the public schema, so the REST API, realtime and apps no longer see them. */
export const ARCHIVE_SCHEMA = 'kodudb_archive'

/**
 * @typedef {{ name: string, type: string, nullable: boolean, default: string | null, primary_key: boolean, identity?: boolean }} DbColumn
 * @typedef {'identity' | 'uuid' | 'none'} Generator How new rows get a value: auto-increment, random uuid, or given by the app.
 * @typedef {{ orig: string | null, name: string, type: string, nullable: boolean, def: string, drop: boolean, generate?: Generator }} EditColumn
 */

/**
 * Statements that turn `original` into `edited`. Column changes use the original table name; a table rename
 * comes last. Throws when the edit is not allowed (dropping a primary key column, empty names).
 * @param {{ name: string, columns: DbColumn[] }} original
 * @param {{ name: string, columns: EditColumn[] }} edited
 * @returns {string[]}
 */
export function alterTableSql(original, edited) {
  const table = `public.${qi(original.name)}`
  const out = []
  for (const col of edited.columns) {
    const name = col.name.trim()
    if (col.orig === null) {
      if (col.drop || !name) continue // a new row the user removed or left empty
      out.push(`alter table ${table} add column ${qi(name)} ${col.type}${col.nullable ? '' : ' not null'}${col.def.trim() ? ` default ${col.def.trim()}` : ''}`)
      continue
    }
    const before = original.columns.find((c) => c.name === col.orig)
    if (!before) throw new Error(`unknown column ${col.orig}`)
    if (col.drop) {
      if (before.primary_key) throw new Error(`${col.orig} is the primary key and cannot be dropped`)
      out.push(`alter table ${table} drop column ${qi(col.orig)}`)
      continue
    }
    if (!name) throw new Error(`column ${col.orig} needs a name`)
    if (name !== col.orig) out.push(`alter table ${table} rename column ${qi(col.orig)} to ${qi(name)}`)
    const ref = qi(name)
    let def = col.def.trim()
    if (col.type !== before.type) {
      const plan = typeChange(before, col, ref)
      for (const s of plan.before) out.push(`alter table ${table} alter column ${ref} ${s}`)
      out.push(`alter table ${table} alter column ${ref} type ${col.type} using ${plan.using}`)
      if (plan.defaultIfEmpty && !def) def = plan.defaultIfEmpty
    }
    let identityKept = before.identity && INTEGER.test(before.type) && INTEGER.test(col.type)
    if (col.generate && (col.generate !== generatorOf(before) || col.type !== before.type)) {
      if (col.generate === 'identity') {
        if (!INTEGER.test(col.type)) throw new Error(`${name}: auto-increment needs an integer type`)
        if (!identityKept) {
          if (before.default) out.push(`alter table ${table} alter column ${ref} drop default`)
          out.push(`alter table ${table} alter column ${ref} add generated by default as identity`)
          // Start after the highest existing value so new rows don't collide.
          out.push(`select setval(pg_get_serial_sequence(${ql(table)}, ${ql(name)}), coalesce(max(${ref}), 0) + 1, false) from ${table}`)
          identityKept = true
        }
      } else if (col.generate === 'uuid') {
        if (col.type !== 'uuid') throw new Error(`${name}: random uuid needs the uuid type`)
        def = 'gen_random_uuid()'
      } else {
        if (identityKept) out.push(`alter table ${table} alter column ${ref} drop identity if exists`)
        identityKept = false
        def = ''
      }
    }
    if (col.nullable !== before.nullable) out.push(`alter table ${table} alter column ${ref} ${col.nullable ? 'drop' : 'set'} not null`)
    if (!identityKept && def !== (before.default ?? '')) out.push(def ? `alter table ${table} alter column ${ref} set default ${def}` : `alter table ${table} alter column ${ref} drop default`)
  }
  const newName = edited.name.trim()
  if (!newName) throw new Error('the table needs a name')
  if (newName !== original.name) out.push(`alter table ${table} rename to ${qi(newName)}`)
  return out
}

const INTEGER = /^(smallint|integer|bigint|int[248]?|serial|bigserial)$/

/** True for integer types (the ones that can auto-increment). @param {string} type */
export const isInteger = (type) => INTEGER.test(type)

/** How a column fills itself in on insert today. A serial (sequence default) counts as auto-increment. @param {DbColumn} c @returns {Generator} */
export function generatorOf(c) {
  if (c.identity || /^nextval\(/.test(c.default ?? '')) return 'identity'
  return /gen_random_uuid\(\)/.test(c.default ?? '') ? 'uuid' : 'none'
}

/** The id column for a new table. @param {Generator} generate */
export const primaryKeyDef = (generate) => ({
  identity: 'id bigint generated by default as identity primary key',
  uuid: 'id uuid primary key default gen_random_uuid()',
  none: 'id bigint primary key',
})[generate]

/**
 * How to convert a column to a new type. A plain cast works for compatible types (integer to bigint, text to
 * uuid). Integer to uuid cannot be cast: the identity is dropped and every row gets a new gen_random_uuid().
 * `col.using` (an SQL expression) overrides the conversion.
 * @param {DbColumn} before @param {EditColumn & { using?: string }} col @param {string} ref
 * @returns {{ before: string[], using: string, defaultIfEmpty?: string }}
 */
export function typeChange(before, col, ref) {
  const fromInt = INTEGER.test(before.type)
  const toInt = INTEGER.test(col.type)
  // An identity only exists on integer columns; leaving the integer family has to remove it first.
  const dropIdentity = fromInt && !toInt ? ['drop identity if exists'] : []
  if (col.using?.trim()) return { before: dropIdentity, using: col.using.trim() }
  if (col.type === 'uuid' && fromInt) {
    return { before: [...dropIdentity, 'drop default'], using: 'gen_random_uuid()', defaultIfEmpty: before.primary_key ? 'gen_random_uuid()' : undefined }
  }
  return { before: dropIdentity, using: `${ref}::${col.type}` }
}

/** True when changing this column's type rewrites its values (warn: references to it must change too). */
export const rewritesValues = (/** @type {DbColumn} */ before, /** @type {string} */ type) => type === 'uuid' && INTEGER.test(before.type)

/** Move a table out of the public schema; data, policies, indexes and triggers move with it. @param {string} name */
export const archiveSql = (name) => [
  `create schema if not exists ${ARCHIVE_SCHEMA}`,
  `alter table public.${qi(name)} set schema ${ARCHIVE_SCHEMA}`,
]

/** Bring an archived table back into the public schema. @param {string} name */
export const restoreSql = (name) => [`alter table ${ARCHIVE_SCHEMA}.${qi(name)} set schema public`]

/** Permanently delete a table (public or archived). @param {string} name @param {boolean} [archived] */
export const dropSql = (name, archived = false) => [`drop table ${archived ? ARCHIVE_SCHEMA : 'public'}.${qi(name)}`]

/** Wrap statements in one transaction, so a failing step changes nothing. @param {string[]} statements */
export const transaction = (statements) => `begin;\n${statements.map((s) => `${s};`).join('\n')}\ncommit;`

/** Lists archived tables. */
export const ARCHIVED_TABLES_SQL = `select c.relname as name, greatest(c.reltuples, 0)::bigint as rows_estimate
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = '${ARCHIVE_SCHEMA}' and c.relkind in ('r', 'p') order by 1`
