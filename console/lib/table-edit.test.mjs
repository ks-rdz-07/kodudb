import assert from 'node:assert/strict'
import { test } from 'node:test'
import { alterTableSql, archiveSql, dropSql, generatorOf, primaryKeyDef, restoreSql, transaction } from './table-edit.mjs'

const original = {
  name: 'orders',
  columns: [
    { name: 'id', type: 'bigint', nullable: false, default: null, primary_key: true },
    { name: 'note', type: 'text', nullable: true, default: null, primary_key: false },
    { name: 'qty', type: 'integer', nullable: true, default: '0', primary_key: false },
  ],
}
const keep = (c) => ({ orig: c.name, name: c.name, type: c.type, nullable: c.nullable, def: c.default ?? '', drop: false })

test('no changes, no statements', () => {
  assert.deepEqual(alterTableSql(original, { name: 'orders', columns: original.columns.map(keep) }), [])
})

test('renames, type, nullability, default, add and drop', () => {
  const cols = original.columns.map(keep)
  cols[1] = { ...cols[1], name: 'comment', nullable: false }
  cols[2] = { ...cols[2], type: 'bigint', def: '' }
  cols.push({ orig: null, name: 'status', type: 'text', nullable: false, def: "'new'", drop: false })
  cols.push({ orig: null, name: '', type: 'text', nullable: true, def: '', drop: false }) // empty new row is ignored
  assert.deepEqual(alterTableSql(original, { name: 'purchase orders', columns: cols }), [
    'alter table public."orders" rename column "note" to "comment"',
    'alter table public."orders" alter column "comment" set not null',
    'alter table public."orders" alter column "qty" type bigint using "qty"::bigint',
    'alter table public."orders" alter column "qty" drop default',
    `alter table public."orders" add column "status" text not null default 'new'`,
    'alter table public."orders" rename to "purchase orders"',
  ])
})

test('drops a column, refuses to drop the primary key', () => {
  const cols = original.columns.map(keep)
  cols[1].drop = true
  assert.deepEqual(alterTableSql(original, { name: 'orders', columns: cols }), ['alter table public."orders" drop column "note"'])
  cols[0].drop = true
  assert.throws(() => alterTableSql(original, { name: 'orders', columns: cols }), /primary key/)
})

test('identifiers are quoted, so names cannot inject SQL', () => {
  const cols = original.columns.map(keep)
  cols[1].name = 'x"; drop table orders; --'
  const [stmt] = alterTableSql(original, { name: 'orders', columns: cols })
  assert.equal(stmt, 'alter table public."orders" rename column "note" to "x""; drop table orders; --"')
})

test('primary key: integer identity to uuid gets new values and a default', () => {
  const cols = original.columns.map(keep)
  cols[0].type = 'uuid'
  assert.deepEqual(alterTableSql(original, { name: 'orders', columns: cols }), [
    'alter table public."orders" alter column "id" drop identity if exists',
    'alter table public."orders" alter column "id" drop default',
    'alter table public."orders" alter column "id" type uuid using gen_random_uuid()',
    'alter table public."orders" alter column "id" set default gen_random_uuid()',
  ])
})

test('primary key: compatible change is a plain cast and keeps the identity', () => {
  const cols = original.columns.map(keep)
  cols[2].type = 'bigint'
  assert.deepEqual(alterTableSql(original, { name: 'orders', columns: cols }), ['alter table public."orders" alter column "qty" type bigint using "qty"::bigint'])
  const pk = original.columns.map(keep)
  pk[0].type = 'integer'
  assert.deepEqual(alterTableSql(original, { name: 'orders', columns: pk }), ['alter table public."orders" alter column "id" type integer using "id"::integer'])
})

test('a custom conversion expression overrides the default cast', () => {
  const cols = original.columns.map(keep)
  cols[1] = { ...cols[1], type: 'integer', using: "nullif(note, '')::integer" }
  assert.deepEqual(alterTableSql(original, { name: 'orders', columns: cols }), [`alter table public."orders" alter column "note" type integer using nullif(note, '')::integer`])
})

test('primary key generator: detect, add, switch off', () => {
  const plain = { name: 'id', type: 'bigint', nullable: false, default: null, primary_key: true }
  assert.equal(generatorOf({ ...plain, identity: true }), 'identity')
  assert.equal(generatorOf({ ...plain, default: "nextval('t_id_seq'::regclass)" }), 'identity')
  assert.equal(generatorOf({ ...plain, type: 'uuid', default: 'gen_random_uuid()' }), 'uuid')
  assert.equal(generatorOf(plain), 'none')

  const t = { name: 'orders', columns: [plain] }
  const on = { ...keep(plain), generate: 'identity' }
  assert.deepEqual(alterTableSql(t, { name: 'orders', columns: [on] }), [
    'alter table public."orders" alter column "id" add generated by default as identity',
    `select setval(pg_get_serial_sequence('public."orders"', 'id'), coalesce(max("id"), 0) + 1, false) from public."orders"`,
  ])
  const ident = { name: 'orders', columns: [{ ...plain, identity: true }] }
  assert.deepEqual(alterTableSql(ident, { name: 'orders', columns: [{ ...keep(plain), generate: 'identity' }] }), [])
  assert.deepEqual(alterTableSql(ident, { name: 'orders', columns: [{ ...keep(plain), generate: 'none' }] }), ['alter table public."orders" alter column "id" drop identity if exists'])
  assert.throws(() => alterTableSql(t, { name: 'orders', columns: [{ ...keep(plain), type: 'text', generate: 'identity' }] }), /integer/)

  const u = { ...plain, type: 'uuid' }
  assert.deepEqual(alterTableSql({ name: 'orders', columns: [u] }, { name: 'orders', columns: [{ ...keep(u), generate: 'uuid' }] }), ['alter table public."orders" alter column "id" set default gen_random_uuid()'])
  assert.match(primaryKeyDef('uuid'), /uuid primary key default gen_random_uuid\(\)/)
})

test('empty table name is refused', () => {
  assert.throws(() => alterTableSql(original, { name: '  ', columns: original.columns.map(keep) }), /needs a name/)
})

test('archive, restore and drop statements', () => {
  assert.deepEqual(archiveSql('orders'), ['create schema if not exists kodudb_archive', 'alter table public."orders" set schema kodudb_archive'])
  assert.deepEqual(restoreSql('orders'), ['alter table kodudb_archive."orders" set schema public'])
  assert.deepEqual(dropSql('orders'), ['drop table public."orders"'])
  assert.deepEqual(dropSql('orders', true), ['drop table kodudb_archive."orders"'])
  assert.equal(transaction(['a', 'b']), 'begin;\na;\nb;\ncommit;')
})
