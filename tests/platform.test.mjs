// Multi-project, branching, schema versioning and GitHub sync, against a running stack.
// GitHub is replaced by a local mock the API container reaches via host.containers.internal.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { after, before, describe, test } from 'node:test'

const env = Object.fromEntries(
  readFileSync(new URL('../.env', import.meta.url), 'utf8').split('\n').filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()]),
)
const API = process.env.KODUDB_URL ?? 'http://127.0.0.1:8787'
const ROOT = env.SECRET_KEY
const RUN = Date.now().toString(36)
const MOCK_PORT = 18999
const MOCK_FROM_API = process.env.MOCK_GITHUB_URL ?? `http://kodudb-ghmock:${MOCK_PORT}`
const TOKEN = 'ghp_test_token'

async function call(path, { key, token, method = 'GET', body } = {}) {
  const headers = { apikey: key }
  if (token) headers.authorization = `Bearer ${token}`
  if (body !== undefined) headers['content-type'] = 'application/json'
  const res = await fetch(API + path, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) })
  const text = await res.text()
  let data = text
  try { data = text ? JSON.parse(text) : null } catch {}
  return { status: res.status, data }
}
const root = (path, opts = {}) => call(path, { ...opts, key: ROOT })

// ---- mock GitHub, run as a container on the stack network so the API can reach it ----
const MOCK = 'kodudb-ghmock'
async function ghState() {
  return (await fetch(`http://127.0.0.1:${MOCK_PORT}/__state`)).json()
}
async function startMock() {
  spawnSync('podman', ['rm', '-f', MOCK])
  const mockFile = fileURLToPath(new URL('./github-mock.mjs', import.meta.url))
  const r = spawnSync('podman', ['run', '-d', '--name', MOCK, '--network', 'kodudb_default', '-p', `127.0.0.1:${MOCK_PORT}:${MOCK_PORT}`,
    '-v', `${mockFile}:/mock.mjs:ro`, 'docker.io/library/node:24-alpine', 'node', '/mock.mjs'], { encoding: 'utf8' })
  assert.equal(r.status, 0, r.stderr)
  for (let i = 0; i < 50; i++) {
    try { return await ghState() } catch { await new Promise((res) => setTimeout(res, 200)) }
  }
  throw new Error('mock GitHub did not start')
}

let shop // created project
let branch // its branch project

before(startMock)
after(async () => {
  if (shop) await root(`/platform/v1/projects/${shop.slug}`, { method: 'DELETE' })
  spawnSync('podman', ['rm', '-f', MOCK])
})

const P = (slug) => `/p/${slug}`
const svc = (p) => (path, opts = {}) => call(P(p.slug) + path, { ...opts, key: p.secret_key })

describe('projects', () => {
  test('rejects bad names and protects the default project', async () => {
    assert.equal((await root('/platform/v1/projects', { method: 'POST', body: { name: '1x' } })).status, 400)
    assert.equal((await root('/platform/v1/projects', { method: 'POST', body: { name: 'default' } })).status, 400)
    assert.equal((await root('/platform/v1/projects/default', { method: 'DELETE' })).status, 400)
    assert.equal((await root('/platform/v1/projects/default/branches', { method: 'POST', body: { name: 'x' } })).status, 400)
  })
  test('only the root service key manages projects', async () => {
    assert.equal((await call('/platform/v1/projects', { key: env.PUBLIC_KEY })).status, 403)
  })
  test('creating a project creates its own database and keys', async () => {
    const r = await root('/platform/v1/projects', { method: 'POST', body: { name: `Shop ${RUN}` } })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    shop = r.data
    assert.equal(shop.slug, `shop-${RUN}`)
    assert.equal(shop.db_name, `p_shop_${RUN}`)
    assert.equal(shop.path, `/p/shop-${RUN}`)
    assert.notEqual(shop.public_key, env.PUBLIC_KEY)
    const dup = await root('/platform/v1/projects', { method: 'POST', body: { name: `Shop ${RUN}` } })
    assert.equal(dup.status, 409)
    const list = await root('/platform/v1/projects')
    assert.ok(list.data.some((p) => p.slug === shop.slug) && list.data[0].slug === 'default')
  })
  test('keys are scoped to their project', async () => {
    assert.equal((await call(`${P(shop.slug)}/meta/v1/tables`, { key: ROOT })).status, 401)
    assert.equal((await call('/meta/v1/tables', { key: shop.secret_key })).status, 401)
    assert.equal((await svc(shop)('/meta/v1/tables')).status, 200)
  })
  test('unknown project is a 404', async () => {
    assert.equal((await call('/p/nope-zz/rest/v1/x', { key: ROOT })).status, 404)
  })
  test('schema, data and users are isolated per project', async () => {
    const s = svc(shop)
    const ddl = await s('/meta/v1/query', { method: 'POST', body: { query: 'create table public.orders (id bigint generated by default as identity primary key, item text not null)' } })
    assert.equal(ddl.status, 200, JSON.stringify(ddl.data))
    const ins = await s('/rest/v1/orders', { method: 'POST', body: [{ item: 'tea' }, { item: 'coffee' }] })
    assert.equal(ins.status, 201)
    assert.equal((await root('/rest/v1/orders')).status, 404) // not in the default project
    const su = await call(`${P(shop.slug)}/auth/v1/signup`, { key: shop.public_key, method: 'POST', body: { email: `member-${RUN}@example.test`, password: 'correct-horse-battery' } })
    assert.equal(su.status, 200)
    const other = await call('/auth/v1/token?grant_type=password', { key: env.PUBLIC_KEY, method: 'POST', body: { email: `member-${RUN}@example.test`, password: 'correct-horse-battery' } })
    assert.equal(other.status, 400)
  })
  test('storage and realtime work under the project prefix', async () => {
    const s = svc(shop)
    assert.equal((await s('/storage/v1/bucket', { method: 'POST', body: { id: 'invoices', public: true } })).status, 200)
    const up = await fetch(`${API}${P(shop.slug)}/storage/v1/object/invoices/a.txt`, { method: 'POST', headers: { apikey: shop.secret_key, 'content-type': 'text/plain' }, body: 'inv' })
    assert.equal(up.status, 200)
    assert.equal(await (await fetch(`${API}${P(shop.slug)}/storage/v1/object/public/invoices/a.txt`)).text(), 'inv')
    assert.equal((await fetch(`${API}/storage/v1/object/public/invoices/a.txt`)).status, 404)

    await s('/meta/v1/query', { method: 'POST', body: { query: 'create trigger kodudb_realtime after insert on public.orders for each row execute function realtime.broadcast_change()' } })
    const ws = new WebSocket(`${API.replace('http', 'ws')}${P(shop.slug)}/realtime/v1/websocket?apikey=${shop.secret_key}`)
    const got = new Promise((resolve) => {
      ws.onmessage = async (m) => {
        const e = JSON.parse(m.data)
        if (e.type === 'subscribed') await s('/rest/v1/orders', { method: 'POST', body: { item: 'cake' } })
        else resolve(e)
      }
      ws.onopen = () => ws.send(JSON.stringify({ type: 'subscribe', table: 'orders' }))
    })
    const e = await got
    ws.close()
    assert.equal(e.record.item, 'cake')
  })
  test('metrics and logs are per project', async () => {
    await new Promise((r) => setTimeout(r, 1500))
    const logs = await svc(shop)('/meta/v1/logs?limit=200')
    assert.ok(logs.data.length > 0 && logs.data.every((l) => l.project === shop.slug))
  })
})

describe('direct connection', () => {
  // Connects from a throwaway client container on the stack network (the database host there is `db`).
  const psql = (c, sql, db = c.database) => {
    const r = spawnSync('podman', ['run', '--rm', '--network', 'kodudb_default', '-e', `PGPASSWORD=${c.password}`, 'docker.io/library/postgres:17-alpine',
      'psql', '-h', 'db', '-U', c.user, '-d', db, '-At', '-c', sql], { encoding: 'utf8' })
    return { ok: r.status === 0, out: r.stdout.trim(), err: r.stderr }
  }
  let conn
  test('returns a limited login role, never the superuser', async () => {
    const r = await root(`/platform/v1/projects/${shop.slug}/connection`)
    assert.equal(r.status, 200, JSON.stringify(r.data))
    conn = r.data
    assert.equal(conn.database, shop.db_name)
    assert.equal(conn.user, `p_shop_${RUN}_direct`)
    assert.notEqual(conn.user, 'postgres')
    assert.ok(conn.uri.startsWith(`postgresql://${conn.user}:${conn.password}@`) && conn.uri.includes(`/${conn.database}?sslmode=`))
    assert.equal((await root(`/platform/v1/projects/${shop.slug}/connection`)).data.password, conn.password) // stable until rotated
    assert.equal((await root('/platform/v1/projects/default/connection')).status, 400)
    assert.equal((await call(`/platform/v1/projects/${shop.slug}/connection`, { key: env.PUBLIC_KEY })).status, 403)
  })
  test('works in its own database and nowhere else', () => {
    const own = psql(conn, 'select count(*) from public.orders')
    assert.ok(own.ok, own.err)
    assert.equal(own.out, '3')
    assert.equal(psql(conn, 'select current_user').out, `p_shop_${RUN}_owner`) // acts as the table owner, so new tables match the API's
    assert.ok(!psql(conn, 'select 1', 'kodudb').ok)
    assert.ok(!psql(conn, 'select 1', 'postgres').ok)
    assert.equal(psql(conn, 'select rolsuper from pg_roles where rolname = current_user').out, 'f')
  })
  test('rotating changes the password and ends the old one', async () => {
    const r = await root(`/platform/v1/projects/${shop.slug}/connection/rotate`, { method: 'POST' })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    assert.notEqual(r.data.password, conn.password)
    assert.ok(!psql(conn, 'select 1').ok)
    assert.ok(psql(r.data, 'select 1').ok)
  })
})

describe('schema versioning', () => {
  test('every DDL statement is recorded as a migration', async () => {
    const m = await svc(shop)('/meta/v1/migrations')
    const tags = m.data.map((x) => x.tag)
    assert.ok(tags.includes('CREATE TABLE'), JSON.stringify(tags)) // implicit identity sequence folds into the table
    assert.ok(tags.includes('CREATE TRIGGER'))
    assert.ok(m.data.some((x) => x.object === 'public.orders' && /create table public\.orders/i.test(x.statement)))
    assert.ok(m.data.every((x) => x.pushed_at === null))
  })
  test('drops are recorded too, DML is not', async () => {
    const s = svc(shop)
    await s('/meta/v1/query', { method: 'POST', body: { query: 'create table public.scratch (x int); drop table public.scratch;' } })
    await s('/rest/v1/orders', { method: 'POST', body: { item: 'dml only' } })
    const m = await s('/meta/v1/migrations')
    assert.ok(m.data.some((x) => x.tag === 'CREATE TABLE, DROP TABLE' && x.object === 'public.scratch'), JSON.stringify(m.data.slice(0, 3)))
    assert.ok(!m.data.some((x) => /insert/i.test(x.tag)))
  })
})

describe('branching and GitHub', () => {
  test('push requires a GitHub connection and a valid repo', async () => {
    assert.equal((await root(`/platform/v1/projects/${shop.slug}/github/push`, { method: 'POST' })).status, 400)
    assert.equal((await root(`/platform/v1/projects/${shop.slug}/github`, { method: 'PUT', body: { repo: 'bad repo' } })).status, 400)
  })
  test('connects GitHub without ever returning the token', async () => {
    const r = await root(`/platform/v1/projects/${shop.slug}/github`, { method: 'PUT', body: { repo: 'acme/backend', token: TOKEN, api_url: MOCK_FROM_API } })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    assert.equal(r.data.github_connected, true)
    assert.ok(!JSON.stringify(r.data).includes(TOKEN))
  })
  test('pushes pending migrations as ordered files on main', async () => {
    const r = await root(`/platform/v1/projects/${shop.slug}/github/push`, { method: 'POST' })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    assert.equal(r.data.pushed.length, 3) // create table, create trigger, create+drop scratch
    const gh = await ghState()
    assert.ok(gh.auth.includes(`Bearer ${TOKEN}`))
    const create = Object.entries(gh.files).find(([k]) => k.startsWith(`main:kodudb/${shop.slug}/migrations/`) && k.endsWith('_create_table.sql'))
    assert.ok(create, Object.keys(gh.files).join('\n'))
    assert.match(create[1], /create table public\.orders/i)
    const m = await svc(shop)('/meta/v1/migrations')
    assert.ok(m.data.every((x) => x.pushed_at !== null))
    const again = await root(`/platform/v1/projects/${shop.slug}/github/push`, { method: 'POST' })
    assert.equal(again.data.pushed.length, 0)
  })
  test('branch clones schema and data into a new database', async () => {
    const r = await root(`/platform/v1/projects/${shop.slug}/branches`, { method: 'POST', body: { name: 'Feature X' } })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    branch = r.data
    assert.equal(branch.slug, `${shop.slug}-feature-x`)
    assert.equal(branch.parent, shop.slug)
    assert.equal(branch.git_branch, 'feature-x')
    assert.equal(branch.github_repo, 'acme/backend')
    const rows = await svc(branch)('/rest/v1/orders?select=item&order=id')
    assert.deepEqual(rows.data.map((x) => x.item), ['tea', 'coffee', 'cake', 'dml only'])
    // the parent keeps serving after being briefly disconnected for the copy
    assert.equal((await svc(shop)('/rest/v1/orders?select=id')).status, 200)
  })
  test('branch changes stay on the branch', async () => {
    await svc(branch)('/meta/v1/query', { method: 'POST', body: { query: 'alter table public.orders add column qty int not null default 1' } })
    const cols = (await svc(shop)('/meta/v1/tables/orders/columns')).data.map((c) => c.name)
    assert.ok(!cols.includes('qty'))
    const bm = await svc(branch)('/meta/v1/migrations')
    assert.equal(bm.data[0].tag, 'ALTER TABLE')
    assert.equal(bm.data[0].pushed_at, null)
    assert.ok(bm.data.slice(1).every((x) => x.pushed_at !== null)) // history inherited from the parent
  })
  test('branch push creates the git branch and only sends new migrations', async () => {
    const before = Object.keys((await ghState()).files).length
    const r = await root(`/platform/v1/projects/${branch.slug}/github/push`, { method: 'POST' })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    const gh = await ghState()
    assert.ok(gh.branches.includes('feature-x'))
    assert.equal(r.data.pushed.length, 1)
    assert.equal(Object.keys(gh.files).length, before + 1)
    assert.ok(Object.keys(gh.files).some((k) => k.startsWith(`feature-x:kodudb/${shop.slug}/migrations/`) && k.endsWith('_alter_table.sql')))
  })
  test('opens a pull request from the branch into its parent branch', async () => {
    const r = await root(`/platform/v1/projects/${branch.slug}/github/pull-request`, { method: 'POST' })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    const gh = await ghState()
    assert.deepEqual([gh.pulls.at(-1).head, gh.pulls.at(-1).base], ['feature-x', 'main'])
    assert.equal((await root(`/platform/v1/projects/${shop.slug}/github/pull-request`, { method: 'POST' })).status, 400)
  })
  test('deleting a project removes its branches and databases', async () => {
    assert.equal((await root(`/platform/v1/projects/${shop.slug}`, { method: 'DELETE' })).status, 204)
    assert.equal((await root(`/platform/v1/projects/${branch.slug}`)).status, 404)
    assert.equal((await call(`${P(shop.slug)}/rest/v1/orders`, { key: shop.public_key })).status, 404)
    const dbs = await root('/meta/v1/query', { method: 'POST', body: { query: `select datname from pg_database where datname like 'p_shop_${RUN}%'` } })
    assert.equal(dbs.data.rows.length, 0)
    shop = null
  })
})

describe('key rotation', () => {
  let proj
  before(async () => {
    proj = (await root('/platform/v1/projects', { method: 'POST', body: { name: `Rotate ${RUN}` } })).data
  })
  after(async () => {
    if (proj) await root(`/platform/v1/projects/${proj.slug}`, { method: 'DELETE' })
  })
  test('rotating a project issues new keys and revokes the old ones and their sessions', async () => {
    const old = svc(proj)
    assert.equal((await old('/meta/v1/tables')).status, 200)
    const user = await call(`${P(proj.slug)}/auth/v1/signup`, { key: proj.public_key, method: 'POST', body: { email: `rot-${RUN}@example.test`, password: 'correct-horse-battery' } })
    const r = await root(`/platform/v1/projects/${proj.slug}/rotate-keys`, { method: 'POST' })
    assert.equal(r.status, 200, JSON.stringify(r.data))
    assert.notEqual(r.data.secret_key, proj.secret_key)
    assert.equal((await old('/meta/v1/tables')).status, 401)
    assert.equal((await call(`${P(proj.slug)}/auth/v1/user`, { key: r.data.public_key, token: user.data.access_token })).status, 401)
    assert.equal((await svc(r.data)('/meta/v1/tables')).status, 200)
    proj = { ...proj, ...r.data }
  })
  test('rotate-all covers every project and reports the default as skipped', async () => {
    const r = await root('/platform/v1/rotate-keys', { method: 'POST' })
    assert.equal(r.status, 200)
    assert.ok(r.data.rotated.includes(proj.slug))
    assert.deepEqual(r.data.skipped, ['default'])
    assert.equal((await svc(proj)('/meta/v1/tables')).status, 401)
  })
  test('the default project explains how to rotate its env keys', async () => {
    const r = await root('/platform/v1/projects/default/rotate-keys', { method: 'POST' })
    assert.equal(r.status, 400)
    assert.match(r.data.error, /gen-env\.mjs --rotate/)
  })
})

describe('database isolation', () => {
  const ENC = env.ENCRYPTION_KEY || env.JWT_SECRET
  let a, b, br
  const q = (p, query) => svc(p)('/meta/v1/query', { method: 'POST', body: { query } })
  const creds = async (slug) => {
    const r = await root('/meta/v1/query', { method: 'POST', body: { query: `select owner_role, pgp_sym_decrypt(owner_password_enc, '${ENC.replaceAll("'", "''")}') from platform.projects where slug = '${slug}'` } })
    return { role: r.data.rows[0][0], password: r.data.rows[0][1] }
  }
  const psql = (c, db) => spawnSync('podman', ['exec', '-e', `PGPASSWORD=${c.password}`, 'kodudb-db-1', 'psql', '-h', '127.0.0.1', '-U', c.role, '-d', db, '-tAc', 'select 1'], { encoding: 'utf8' })

  before(async () => {
    a = (await root('/platform/v1/projects', { method: 'POST', body: { name: `Iso A ${RUN}` } })).data
    b = (await root('/platform/v1/projects', { method: 'POST', body: { name: `Iso B ${RUN}` } })).data
  })
  after(async () => {
    for (const p of [a, b]) if (p) await root(`/platform/v1/projects/${p.slug}`, { method: 'DELETE' })
  })

  test('project SQL runs as its own non-superuser role', async () => {
    const r = await q(a, "select current_user, current_setting('is_superuser')")
    assert.equal(r.status, 200, JSON.stringify(r.data))
    assert.deepEqual(r.data.rows[0], [`p_iso_a_${RUN}_owner`, 'off'])
  })

  test('server-level and cross-database statements are refused', async () => {
    for (const stmt of ["create extension dblink", "copy (select 1) to program 'id'", "alter system set work_mem = '1MB'", 'create role sneaky', 'create database sneaky']) {
      const r = await q(a, stmt)
      assert.notEqual(r.status, 200, `${stmt} was allowed`)
    }
  })

  test("a project's role cannot connect to another project's database", async () => {
    const ca = await creds(a.slug)
    const own = psql(ca, a.db_name)
    assert.equal(own.stdout.trim(), '1', own.stderr)
    const other = psql(ca, b.db_name)
    assert.notEqual(other.status, 0)
    assert.match(other.stderr, /permission denied/i)
    assert.notEqual(psql(ca, 'kodudb').status, 0) // nor the platform database
  })

  test('the project still works end to end as its own role', async () => {
    assert.equal((await q(a, 'create table public.notes (id bigint generated by default as identity primary key, body text)')).status, 200)
    assert.equal((await svc(a)('/rest/v1/notes', { method: 'POST', body: { body: 'hi' } })).status, 201)
    assert.equal((await call(`${P(a.slug)}/rest/v1/notes`, { key: a.public_key })).status, 200)
    const m = await svc(a)('/meta/v1/migrations')
    assert.ok(m.data.some((x) => x.object === 'public.notes'))
  })

  test('concurrent first requests share one connection pool', async () => {
    const fresh = (await root('/platform/v1/projects', { method: 'POST', body: { name: `Iso C ${RUN}` } })).data
    try {
      const rs = await Promise.all(Array.from({ length: 15 }, () => svc(fresh)('/meta/v1/tables')))
      assert.ok(rs.every((r) => r.status === 200))
      const conns = await root('/meta/v1/query', { method: 'POST', body: { query: `select count(*) from pg_stat_activity where usename = 'p_iso_c_${RUN}_owner'` } })
      assert.ok(Number(conns.data.rows[0][0]) <= 6, `connections: ${conns.data.rows[0][0]} (pool of 5 + listener)`)
    } finally {
      await root(`/platform/v1/projects/${fresh.slug}`, { method: 'DELETE' })
    }
  })

  test('extensions are enabled through the platform, not project SQL', async () => {
    const on = await root(`/platform/v1/projects/${a.slug}/extensions`, { method: 'POST', body: { name: 'pg_trgm', enabled: true } })
    assert.equal(on.status, 200, JSON.stringify(on.data))
    assert.equal((await q(a, "select extname from pg_extension where extname = 'pg_trgm'")).data.rows.length, 1)
    assert.equal((await root(`/platform/v1/projects/${a.slug}/extensions`, { method: 'POST', body: { name: 'nope_ext', enabled: true } })).status, 400)
    const asProject = await call(`/platform/v1/projects/${a.slug}/extensions`, { key: a.secret_key, method: 'POST', body: { name: 'pg_trgm', enabled: false } })
    assert.ok([401, 403].includes(asProject.status))
  })

  test('a branch is owned by its own role and cannot reach its parent', async () => {
    br = (await root(`/platform/v1/projects/${a.slug}/branches`, { method: 'POST', body: { name: 'iso' } })).data
    assert.ok(br?.slug, 'branch created')
    const who = await q(br, "select current_user, (select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and pg_get_userbyid(c.relowner) <> current_user and c.relkind in ('r','v','m'))")
    assert.deepEqual(who.data.rows[0], [`p_iso_a_${RUN}_iso_owner`, '0'])
    assert.equal((await svc(br)('/rest/v1/notes')).data.length, 1)
    assert.notEqual(psql(await creds(br.slug), a.db_name).status, 0)
    assert.equal((await q(a, 'select count(*) from public.notes')).status, 200) // parent still serves after the clone
  })
})
