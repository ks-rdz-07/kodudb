describe('realtime', () => {
  function listen(token) {
    const ws = new WebSocket(`${API.replace('http', 'ws')}/realtime/v1/websocket?apikey=${ANON}&token=${token}`)
    const events = []
    const ready = new Promise((resolve) => {
      ws.onmessage = (m) => {
        const e = JSON.parse(m.data)
        if (e.type === 'subscribed') resolve()
        else events.push(e)
      }
      ws.onopen = () => ws.send(JSON.stringify({ type: 'subscribe', table: TABLE }))
    })
    return { ws, events, ready }
  }
  test('owner receives their changes; other users do not', async () => {
    const mine = listen(a.access_token)
    const other = listen(b.access_token)
    await Promise.all([mine.ready, other.ready])
    await call(`/rest/v1/${TABLE}`, { token: a.access_token, method: 'POST', body: { title: 'live' } })
    await new Promise((r) => setTimeout(r, 1000))
    mine.ws.close()
    other.ws.close()
    assert.ok(mine.events.some((e) => e.type === 'INSERT' && e.record.title === 'live'), JSON.stringify(mine.events))
    assert.equal(other.events.length, 0)
  })
  test('rejects bad subscribe messages', async () => {
    const ws = new WebSocket(`${API.replace('http', 'ws')}/realtime/v1/websocket?apikey=${ANON}`)
    const reply = await new Promise((resolve) => {
      ws.onopen = () => ws.send(JSON.stringify({ type: 'subscribe', table: 'x"; drop' }))
      ws.onmessage = (m) => resolve(JSON.parse(m.data))
    })
    ws.close()
    assert.equal(reply.type, 'error')
  })
})

